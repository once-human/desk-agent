package nativehost

import (
	"crypto/sha256"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// HostName is the native messaging host name the extension connects to.
const HostName = "desk_agent"

// ChromiumExtensionID is the ID of the Chromium extension. It is fixed by the
// public `key` in extension/manifest.chromium.json, so it is the same on every
// machine that loads the unpacked extension.
const ChromiumExtensionID = "niohkiipopeggalllikokelcdfghlgic"

// GeckoExtensionID is the Firefox add-on id from extension/manifest.firefox.json.
const GeckoExtensionID = "desk-agent@onkaryaglewad.in"

// Target is one place a native messaging manifest goes.
type Target struct {
	Browser string // display name
	Family  string // "firefox" or "chromium"
	Dir     string // the native-messaging-hosts directory
	Parent  string // the browser's own config dir; if absent, the browser is not installed
}

// Targets lists the known per-user manifest locations under home.
func Targets(home string) []Target {
	ff := func(name, dot string) Target {
		return Target{name, "firefox", filepath.Join(home, dot, "native-messaging-hosts"), filepath.Join(home, dot)}
	}
	cr := func(name, rel string) Target {
		p := filepath.Join(home, ".config", rel)
		return Target{name, "chromium", filepath.Join(p, "NativeMessagingHosts"), p}
	}
	return []Target{
		ff("Firefox", ".mozilla"),
		ff("LibreWolf", ".librewolf"),
		ff("Floorp", ".floorp"),
		ff("Zen", ".zen"),
		cr("Chromium", "chromium"),
		cr("Google Chrome", "google-chrome"),
		cr("Brave", "BraveSoftware/Brave-Browser"),
		cr("Vivaldi", "vivaldi"),
		cr("Microsoft Edge", "microsoft-edge"),
		cr("Thorium", "thorium"),
	}
}

// Manifest builds the manifest JSON for a family. hostPath must be absolute.
func Manifest(family, hostPath string) ([]byte, error) {
	if !filepath.IsAbs(hostPath) {
		return nil, fmt.Errorf("native host path must be absolute: %q", hostPath)
	}
	m := map[string]any{
		"name":        HostName,
		"description": "desk-agent: forwards the active tab's hostname to the local desk-agent",
		"path":        hostPath,
		"type":        "stdio",
	}
	switch family {
	case "firefox":
		m["allowed_extensions"] = []string{GeckoExtensionID}
	case "chromium":
		m["allowed_origins"] = []string{"chrome-extension://" + ChromiumExtensionID + "/"}
	default:
		return nil, fmt.Errorf("unknown family %q", family)
	}
	return json.MarshalIndent(m, "", "  ")
}

// WriteWrapper writes the small launcher the manifests point at. Browsers
// start the host with no subcommand, so the wrapper adds it. It returns the
// wrapper's path.
func WriteWrapper(dataDir, binary string) (string, error) {
	if !filepath.IsAbs(binary) {
		return "", fmt.Errorf("binary path must be absolute: %q", binary)
	}
	if err := os.MkdirAll(dataDir, 0o700); err != nil {
		return "", err
	}
	p := filepath.Join(dataDir, "native-host")
	quoted := "'" + strings.ReplaceAll(binary, "'", `'\''`) + "'"
	script := "#!/bin/sh\n# Generated by `desk-agent install-native-host`. Do not edit.\nexec " + quoted + " native-host \"$@\"\n"
	tmp := p + ".tmp"
	if err := os.WriteFile(tmp, []byte(script), 0o755); err != nil {
		return "", err
	}
	if err := os.Chmod(tmp, 0o755); err != nil {
		return "", err
	}
	return p, os.Rename(tmp, p)
}

// Install writes manifests for every installed browser (or every known one
// when all is true). It returns the files written.
func Install(home, dataDir, binary string, all bool) ([]string, error) {
	wrapper, err := WriteWrapper(dataDir, binary)
	if err != nil {
		return nil, err
	}
	var written []string
	for _, t := range Targets(home) {
		if !all {
			if st, err := os.Stat(t.Parent); err != nil || !st.IsDir() {
				continue
			}
		}
		data, err := Manifest(t.Family, wrapper)
		if err != nil {
			return written, err
		}
		if err := os.MkdirAll(t.Dir, 0o755); err != nil {
			return written, err
		}
		p := filepath.Join(t.Dir, HostName+".json")
		tmp := p + ".tmp"
		if err := os.WriteFile(tmp, append(data, '\n'), 0o644); err != nil {
			return written, err
		}
		if err := os.Rename(tmp, p); err != nil {
			return written, err
		}
		written = append(written, p)
	}
	return written, nil
}

// Remove deletes the manifests (and the wrapper) that Install wrote.
func Remove(home, dataDir string) ([]string, error) {
	var removed []string
	for _, t := range Targets(home) {
		p := filepath.Join(t.Dir, HostName+".json")
		if err := os.Remove(p); err == nil {
			removed = append(removed, p)
		}
	}
	w := filepath.Join(dataDir, "native-host")
	if err := os.Remove(w); err == nil {
		removed = append(removed, w)
	}
	return removed, nil
}

// ChromiumIDFromKey derives a Chromium extension id from the base64 public key
// in a manifest: the first 16 bytes of the SHA-256 of the DER key, with each
// hex digit mapped 0-f to a-p.
func ChromiumIDFromKey(b64 string) string {
	der, err := base64.StdEncoding.DecodeString(b64)
	if err != nil {
		return ""
	}
	sum := sha256.Sum256(der)
	out := make([]byte, 32)
	const hexd = "0123456789abcdef"
	for i := 0; i < 16; i++ {
		out[2*i] = 'a' + byte(strings.IndexByte(hexd, hexd[sum[i]>>4]))
		out[2*i+1] = 'a' + byte(strings.IndexByte(hexd, hexd[sum[i]&0xf]))
	}
	return string(out)
}
